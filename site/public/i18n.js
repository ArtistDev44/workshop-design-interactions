const LANGUES = [
	{ code: 'fr', libelle: 'Français' },
	{ code: 'en', libelle: 'English' },
];
const CLE_LANGUE = 'pxe-nte001-langue';

function t(cle, v) {
	let s = (TRADUCTIONS[Langue.actuelle] || {})[cle];
	if (s === undefined) s = TRADUCTIONS.fr[cle];
	if (s === undefined) return '[À COMPLÉTER]';
	if (v) s = s.replace(/\{(\w+)\}/g, (m, k) => (v[k] === undefined || v[k] === null ? '' : String(v[k])));
	return s;
}
/** t() si la clé existe, sinon la valeur brute (ex. type d'incident venu des données) */
function tSi(cle, brut) {
	return TRADUCTIONS.fr[cle] !== undefined ? t(cle) : brut;
}

class Texte {
	constructor(cle, v) {
		this.cle = cle;
		this.v = v;
	}
	toString() {
		return t(this.cle, this.v);
	}
	toJSON() {
		return this.toString();
	}
	get length() {
		return this.toString().length;
	}
}
const T = (cle, v) => new Texte(cle, v);

/** Liste différée : éléments (Texte ou chaînes) joints à l'affichage, première lettre en capitale si demandé */
class ListeTextes {
	constructor(items, sep, majuscule) {
		this.items = items;
		this.sep = sep;
		this.majuscule = majuscule;
	}
	toString() {
		const s = this.items.map(String).join(this.sep);
		return this.majuscule ? s.charAt(0).toUpperCase() + s.slice(1) : s;
	}
	toJSON() {
		return this.toString();
	}
}
const Liste = (items, sep, majuscule) => new ListeTextes(items, sep || ', ', majuscule);

/** Date ISO → date longue dans la langue active (le format suit la langue, la date reste la donnée réelle) */
function localeActive() {
	return t('locale');
}

const Langue = {
	actuelle: 'fr',
	ecouteurs: [],
	/** Ordre : paramètre d'URL ?lang= (lien partagé, prioritaire) → localStorage → navigator.language → fr */
	detecter() {
		let code = null;
		try {
			code = new URLSearchParams(location.search).get('lang');
		} catch (e) {}
		if (!TRADUCTIONS[code]) {
			try {
				code = localStorage.getItem(CLE_LANGUE);
			} catch (e) {}
		}
		if (!TRADUCTIONS[code]) {
			const n = (typeof navigator !== 'undefined' && navigator.language ? navigator.language : '').slice(0, 2).toLowerCase();
			code = TRADUCTIONS[n] ? n : 'fr';
		}
		this.changer(code, true);
	},
	/** Change la langue sans toucher à la partie (jauges, dossier en cours, journal conservés) */
	changer(code, initial) {
		if (!TRADUCTIONS[code]) return;
		this.actuelle = code;
		if (typeof document !== 'undefined') {
			document.documentElement.lang = code;
			document.title = t('page.titre');
			const scene = document.getElementById('scene');
			if (scene) scene.setAttribute('aria-label', t('page.aria'));
		}
		try {
			localStorage.setItem(CLE_LANGUE, code);
		} catch (e) {}
		if (!initial) this.ecouteurs.forEach((f) => f(code));
	},
	suivante() {
		const i = LANGUES.findIndex((l) => l.code === this.actuelle);
		this.changer(LANGUES[(i + 1) % LANGUES.length].code);
	},
};

/** Annonce pour les lecteurs d'écran (région aria-live de index.html), toujours dans la langue active */
function annoncer(texte) {
	const el = typeof document !== 'undefined' && document.getElementById('annonces');
	if (el) el.textContent = String(texte);
}

// p5 : text() et textWidth() acceptent les textes différés (Texte, Liste) — convertis à chaque image
if (typeof p5 !== 'undefined') {
	['text', 'textWidth'].forEach((nom) => {
		const origine = p5.prototype[nom];
		p5.prototype[nom] = function (s, ...reste) {
			return origine.call(this, s instanceof Texte || s instanceof ListeTextes ? String(s) : s, ...reste);
		};
	});
}
