const CLE_LANGUE = 'pxe-nte001-langue';

function t(cle, v) {
	let s = (TRADUCTIONS[Langue.actuelle] || {})[cle];
	if (s === undefined) s = TRADUCTIONS.fr[cle];
	if (s === undefined) return '[À COMPLÉTER]';
	if (v) s = s.replace(/\{(\w+)\}/g, (m, k) => (v[k] === undefined || v[k] === null ? '' : String(v[k])));
	return s;
}
/** t() si la clé existe, sinon la valeur brute (ex. type d'incident venu des données) */
function tSi(cle, brut) {
	return TRADUCTIONS.fr[cle] !== undefined ? t(cle) : brut;
}

class Texte {
	constructor(cle, v) {
		this.cle = cle;
		this.v = v;
	}
	toString() {
		return t(this.cle, this.v);
	}
	toJSON() {
		return this.toString();
	}
	get length() {
		return this.toString().length;
	}
}
const T = (cle, v) => new Texte(cle, v);

/** Liste différée : éléments (Texte ou chaînes) joints à l'affichage, première lettre en capitale si demandé */
class ListeTextes {
	constructor(items, sep, majuscule) {
		this.items = items;
		this.sep = sep;
		this.majuscule = majuscule;
	}
	toString() {
		const s = this.items.map(String).join(this.sep);
		return this.majuscule ? s.charAt(0).toUpperCase() + s.slice(1) : s;
	}
	toJSON() {
		return this.toString();
	}
}
const Liste = (items, sep, majuscule) => new ListeTextes(items, sep || ', ', majuscule);

